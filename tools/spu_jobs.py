"""Helpers for tools/lift_spu.sh.

  spu_jobs.py wrap <elf> <images_dir> <SPU_JOBS>
      Write each SPURS job binary as an SPU ELF at base 0 (spurs_job_<VA>.elf).
      SPU_JOBS is "sections" (every .bin_objs.<name> section) or "va:size va:size ...";
      VAs are mapped to file offsets through the ELF's program headers.
  spu_jobs.py table-entries <images_dir>
      For each extracted SPU thread image, code addresses stored in its data segment that
      follow a return or branch (function-pointer tables the lifter cannot reach by
      branches), as build_spu_workloads.py --extra-funcs arguments.
  spu_jobs.py registry <spu_workloads.c> <out.c>
      The job-by-address registry (spu_workload_register_ea) from the workload table.
"""
import glob, os, re, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def ppu_segments(d):
    phoff = struct.unpack('>Q', d[0x20:0x28])[0]
    n = struct.unpack('>H', d[0x38:0x3a])[0]
    out = []
    for i in range(n):
        o = phoff + i * 56
        t, f, off, va, pa, fs, ms, al = struct.unpack('>IIQQQQQQ', d[o:o + 56])
        if t == 1 and fs:
            out.append((va, off, fs))
    return out


def va_to_off(segs, va):
    for v, o, fs in segs:
        if v <= va < v + fs:
            return o + va - v
    raise SystemExit(f'VA 0x{va:X} is in no PT_LOAD segment')


def ppu_sections(d):
    shoff = struct.unpack('>Q', d[0x28:0x30])[0]
    n, si = struct.unpack('>HH', d[0x3c:0x40])
    sh = lambda i: struct.unpack('>IIQQQQIIQQ', d[shoff + i * 64:shoff + i * 64 + 64])
    strtab = sh(si)[4]
    for i in range(n):
        nm, t, f, va, off, size = sh(i)[:6]
        yield d[strtab + nm:d.index(b'\0', strtab + nm)].decode(), va, off, size


def wrap(elf, images, spec):
    d = open(elf, 'rb').read()
    jobs = []
    if spec.strip() == 'sections':
        for name, va, off, size in ppu_sections(d):
            if name.startswith('.bin_objs.'):
                jobs.append((va, off, size, name[10:]))
    else:
        segs = ppu_segments(d)
        for item in spec.split():
            va, size = (int(x, 0) for x in item.split(':'))
            jobs.append((va, va_to_off(segs, va), size, ''))
    tmp = os.path.join(images, '..', 'job.bin')
    for va, off, size, name in jobs:
        open(tmp, 'wb').write(d[off:off + size])
        subprocess.run([sys.executable, os.path.join(HERE, '..', 'ps3recomp', 'tools', 'wrap_spu_elf.py'), tmp,
                        '--base', '0x0', '--entry', '0x0', '--out', os.path.join(images, f'spurs_job_{va:08X}.elf')],
                       check=True, stdout=subprocess.DEVNULL)
        print(f'  job {va:08X} {size:6X} {name}')
    os.remove(tmp)
    print('wrapped', len(jobs), 'jobs')


def table_entries(images):
    out = []
    for p in sorted(glob.glob(os.path.join(images, 'spu_*.elf'))):
        d = open(p, 'rb').read()
        ph, n = struct.unpack('>I', d[0x1c:0x20])[0], struct.unpack('>H', d[0x2c:0x2e])[0]
        segs = [struct.unpack('>8I', d[ph + i * 32:ph + i * 32 + 32]) for i in range(n)]
        loads = [s for s in segs if s[0] == 1]
        code = next(s for s in loads if s[6] & 1)
        rest = [s for s in loads if not s[6] & 1]
        c0, c1 = code[2], code[2] + code[4]
        ins = lambda a: struct.unpack('>I', d[code[1] + a - c0:code[1] + a - c0 + 4])[0]
        hits = set()
        for s in rest:
            for i in range(0, s[4] - 3, 4):
                v = struct.unpack('>I', d[s[1] + i:s[1] + i + 4])[0]
                if not (c0 + 8 <= v < c1 and v % 4 == 0):
                    continue
                q = v - 4
                while q > c0 and ins(q) in (0x00200000, 0x40200000):   # lnop / nop padding
                    q -= 4
                if ins(q) == 0x35000000 or ins(q) >> 23 in (0x64, 0x66):  # bi $lr / br
                    hits.add(v)
        if hits:
            out.append('--extra-funcs ' + os.path.basename(p)[:-4] + '=' + ','.join(hex(h) for h in sorted(hits)))
    print(' '.join(out))


def registry(workloads, out_c):
    s = open(workloads, encoding='utf-8').read()
    rows = re.findall(r'spu_workload_register_img\(0x[0-9A-F]+ULL, (spurs_job_([0-9A-F]{8})_spu_func_\w+), (\d+), "spurs_job_\2"\)', s)
    out = ['/* Generated by tools/spu_jobs.py: SPURS job binaries by guest address (spu_workload_register_ea). */',
           '#include "spu_context.h"', 'typedef void (*spu_fn)(spu_context*);',
           'extern void spu_workload_register_ea(unsigned int ea, spu_fn fn, int image_id);']
    out += [f'extern void {fn}(spu_context*);' for fn, ea, iid in rows]
    out.append('static void game_spu_register_jobs(void)\n{')
    out += [f'    spu_workload_register_ea(0x{ea}u, {fn}, {iid});' for fn, ea, iid in rows]
    out.append('}\n__attribute__((constructor)) static void game_spu_jobs_ctor(void) { game_spu_register_jobs(); }')
    open(out_c, 'w').write('\n'.join(out) + '\n')
    print('job registrations:', len(rows))


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'wrap':
        wrap(sys.argv[2], sys.argv[3], sys.argv[4])
    elif cmd == 'table-entries':
        table_entries(sys.argv[2])
    elif cmd == 'registry':
        registry(sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)
